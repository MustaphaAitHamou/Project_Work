"use client";

import { useActionState } from "react";
import { useLocale, useTranslations } from "next-intl";
import { ActionForm } from "@/components/forms/action-form";
import { FormField } from "@/components/forms/form-field";
import { FormMessage } from "@/components/forms/form-message";
import { SubmitButton } from "@/components/forms/submit-button";
import { Input } from "@/components/ui/input";
import { initialActionState, type ActionState } from "@/lib/action-state";
import { startTotpEnrollmentAction, verifyTotpAction, type TotpEnrollment } from "./actions";

export function VerifyForm({ factorId }: { factorId: string }) {
  const t = useTranslations("adminSecurity");
  const locale = useLocale();
  const [state, action] = useActionState(verifyTotpAction, initialActionState);
  return (
    <ActionForm action={action} className="space-y-4" noValidate>
      <input type="hidden" name="locale" value={locale} />
      <input type="hidden" name="factorId" value={factorId} />
      <FormMessage state={state} />
      <FormField id="code" label={t("codeLabel")} required error={state.fieldErrors?.code}>
        {(p) => <Input {...p} name="code" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9]{6}" maxLength={7} autoFocus />}
      </FormField>
      <SubmitButton className="w-full">{t("verify")}</SubmitButton>
    </ActionForm>
  );
}

export function EnrollPanel() {
  const t = useTranslations("adminSecurity");
  const locale = useLocale();
  const [state, start] = useActionState(startTotpEnrollmentAction, initialActionState as ActionState<TotpEnrollment>);
  if (!state.ok || !state.data) {
    return (
      <ActionForm action={start} className="space-y-4">
        <input type="hidden" name="locale" value={locale} />
        <FormMessage state={state} />
        <SubmitButton className="w-full">{t("start")}</SubmitButton>
      </ActionForm>
    );
  }
  return (
    <div className="space-y-4">
      <p className="text-sm">{t("step1")}</p>
      {/* eslint-disable-next-line @next/next/no-img-element -- SVG data URI generated by Supabase Auth */}
      <img src={state.data.qrCode} alt={t("qrAlt")} width={192} height={192} className="mx-auto rounded-md bg-white p-2" />
      <p className="text-sm">
        {t("step2")}{" "}
        <code data-testid="totp-secret" className="break-all rounded bg-muted px-1.5 py-0.5 font-mono text-xs" dir="ltr">
          {state.data.secret}
        </code>
      </p>
      <p className="text-sm">{t("step3")}</p>
      <VerifyForm factorId={state.data.factorId} />
    </div>
  );
}

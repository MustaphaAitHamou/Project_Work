#!/usr/bin/env node
// Generates the geographic reference migrations (regions and cities) for the
// supported markets from the GeoNames-derived `cities.json` package (CC BY 4.0).
//
//   node scripts/generate-geo-sql.mjs
//
// Output:
//   supabase/migrations/20261103091600_geo_regions.sql
//   supabase/migrations/20261103091700_geo_cities.sql
//
// Attribution: data © GeoNames (https://www.geonames.org), CC BY 4.0.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const cities = JSON.parse(readFileSync(require.resolve("cities.json/cities.json"), "utf8"));
const admin1 = JSON.parse(readFileSync(require.resolve("cities.json/admin1.json"), "utf8"));

const COUNTRIES = ["FR", "DZ", "CA", "US", "CH", "LU", "ES", "GB", "BE"];
// French overseas regions are distinct GeoNames countries; they belong to France.
const FR_OVERSEAS = { GP: "Guadeloupe", MQ: "Martinique", GF: "Guyane", RE: "La Réunion", YT: "Mayotte" };

// Local / official names preferred over GeoNames English exonyms.
const REGION_NAME_OVERRIDES = {
  FR: { "94": "Corse", "53": "Bretagne", "75": "Nouvelle-Aquitaine", "28": "Normandie" },
  ES: {
    "31": "Región de Murcia", "07": "Illes Balears", "51": "Andalucía", "53": "Canarias", "54": "Castilla-La Mancha",
    "60": "Comunitat Valenciana", "34": "Principado de Asturias", "32": "Comunidad Foral de Navarra",
    "29": "Comunidad de Madrid", "52": "Aragón", "55": "Castilla y León", "56": "Cataluña", "59": "País Vasco",
  },
  CH: {
    ZH: "Zürich", BE: "Bern / Berne", LU: "Luzern", FR: "Fribourg / Freiburg", BS: "Basel-Stadt", SG: "St. Gallen",
    GR: "Graubünden / Grigioni / Grischun", VS: "Valais / Wallis", GE: "Genève",
  },
  BE: { BRU: "Bruxelles-Capitale / Brussels Hoofdstedelijk Gewest", WAL: "Wallonie", VLG: "Vlaanderen / Flandre" },
  CA: { "10": "Québec" },
  DZ: { "01": "Alger", "40": "Boumerdès", "06": "Médéa", "10": "Saïda", "45": "Ghardaïa" },
};

const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);

// Regions
const regions = [];
const regionKeys = new Set();
for (const a of admin1) {
  const [cc, code] = a.code.split(".");
  if (!COUNTRIES.includes(cc) || !code) continue;
  const name = REGION_NAME_OVERRIDES[cc]?.[code] ?? a.name;
  regions.push({ cc, code, name });
  regionKeys.add(`${cc}.${code}`);
}
for (const [code, name] of Object.entries(FR_OVERSEAS)) {
  regions.push({ cc: "FR", code, name });
  regionKeys.add(`FR.${code}`);
}
regions.sort((a, b) => a.cc.localeCompare(b.cc) || a.name.localeCompare(b.name, "fr"));

let regionSql = `-- Generated by scripts/generate-geo-sql.mjs — do not edit by hand.
-- First-level administrative divisions. Data © GeoNames (CC BY 4.0), names localised where relevant.
insert into public.geo_regions (country_code, code, name) values
${regions.map((r) => `  (${q(r.cc)}, ${q(r.code)}, ${q(r.name)})`).join(",\n")}
on conflict (country_code, code) do update set name = excluded.name;
`;

// Cities
const seen = new Set();
const rows = [];
const norm = (s) => s.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase().trim();
for (const c of cities) {
  let cc = c.country;
  let region = c.admin1 || null;
  if (FR_OVERSEAS[cc]) {
    region = cc;
    cc = "FR";
  } else if (!COUNTRIES.includes(cc)) {
    continue;
  }
  if (region && !regionKeys.has(`${cc}.${region}`)) region = null;
  const key = `${cc}|${region}|${norm(c.name)}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const lat = Number(c.lat);
  const lng = Number(c.lng);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) continue;
  rows.push({ cc, region, name: c.name, lat: lat.toFixed(5), lng: lng.toFixed(5) });
}
rows.sort((a, b) => a.cc.localeCompare(b.cc) || String(a.region).localeCompare(String(b.region)) || a.name.localeCompare(b.name));

const chunks = [];
for (let i = 0; i < rows.length; i += 2000) {
  const part = rows.slice(i, i + 2000);
  chunks.push(
    `insert into public.geo_cities (country_code, region_code, name, latitude, longitude) values\n` +
      part.map((r) => `(${q(r.cc)},${q(r.region)},${q(r.name)},${r.lat},${r.lng})`).join(",\n") +
      ";",
  );
}
const citySql = `-- Generated by scripts/generate-geo-sql.mjs — do not edit by hand.
-- ${rows.length} cities (population > 1000 or administrative seats). Data © GeoNames (CC BY 4.0).
${chunks.join("\n\n")}
`;

writeFileSync(path.join(root, "supabase/migrations/20261103091600_geo_regions.sql"), regionSql);
writeFileSync(path.join(root, "supabase/migrations/20261103091700_geo_cities.sql"), citySql);
console.log(`regions: ${regions.length}, cities: ${rows.length}`);
